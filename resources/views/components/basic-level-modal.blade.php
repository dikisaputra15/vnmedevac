          <div class="tab-pane fade show active" id="class-b-overview" role="tabpanel" aria-labelledby="class-b-overview-tab" tabindex="0">
            <p class="p-modal text-justify">Basic Level (Cấp Cơ Bản / CCB) is the second professional-technical level under the same Decree 96/2023/NĐ-CP framework. It applies to hospitals and health centers with inpatient beds that score below 70 points on the Appendix V scoring instrument. This level accounts for the large majority of hospitals nationwide — in Hanoi's initial 2024 classification exercise, for example, 91% of hospitals citywide were classified as CCB, with the remaining 9% reaching CCS.</p>
          </div>
          <div class="tab-pane fade" id="class-b-role" role="tabpanel" aria-labelledby="class-b-role-tab" tabindex="0">
            <ul>
              <li>Provide secondary-level referral care for common and moderately complex medical, surgical, obstetric, pediatric, and emergency cases.</li>
              <li>Stabilize and refer highly complex, subspecialist, or high-risk cases to CCS facilities.</li>
              <li>Serve as the principal inpatient referral point for CBD facilities within their catchment area.</li>
              <li>May provide limited postgraduate or undergraduate clinical training placements where capacity allows.</li>
            </ul>
          </div>
          <div class="tab-pane fade" id="class-b-services" role="tabpanel" aria-labelledby="class-b-services-tab" tabindex="0">
            <p class="p-modal text-justify">A facility scoring below 70 points on the Appendix V instrument is classified as CCB. Within this level, the score band of 50 to under 70 points carries a specific financing consequence: from 1 July 2026, patients using social health insurance (BHYT) for self-referred outpatient care at these facilities are reimbursed at 50% of the applicable benefit rate, rather than being excluded from coverage as under prior rules.</p>
            <ul>
              <li>Represented examples include Cần Thơ University of Medicine and Pharmacy Hospital (65 points), Hữu Nghị Hospital (61 points), National Psychiatric Hospital No. 2 (60 points), and Việt Nam – Cuba Đồng Hới Friendship Hospital (50 points).</li>
            </ul>
            <p><strong>Typical Bed Capacity</strong></p>
            <ul>
              <li>Ranges widely from approximately 50 to 800 beds, reflecting both small district-level hospitals and larger former provincial or central-tier institutions that scored below the CCS threshold.</li>
            </ul>
            <p><strong>Core Capability Areas</strong></p>
            <ul>
              <li>Moderate technique approval rate against the Ministry of Health's technique catalogue, generally with limited or no approval for special-category techniques.</li>
              <li>Standard general specialties: internal medicine, pediatrics, obstetrics and gynecology, and general surgery.</li>
              <li>Clinical staffing meeting baseline qualification requirements, with a smaller proportion of doctoral or Level II specialist staff than CCS facilities.</li>
              <li>Limited participation in technical support to other facilities or in national-level scientific research.</li>
            </ul>
            <p><strong>Diagnostic &amp; Support Infrastructure</strong></p>
            <ul>
              <li>24-hour emergency department.</li>
              <li>Operating room with general anesthesia capability.</li>
              <li>Standard clinical laboratory and imaging (X-ray, ultrasound; CT where available).</li>
              <li>Maternity and inpatient nursing services.</li>
              <li>Blood storage or transfusion support, capacity depending on facility.</li>
            </ul>
            <p class="p-modal text-justify"><em><strong>Note:</strong> This classification is aligned with Decree No. 96/2023/NĐ-CP (Article 89 and Appendix V) and Công văn 5845/BYT-KCB (2024).</em></p>
