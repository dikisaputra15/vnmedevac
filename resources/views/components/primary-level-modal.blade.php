          <div class="tab-pane fade show active" id="class-d-overview" role="tabpanel" aria-labelledby="class-d-overview-tab" tabindex="0">
            <p class="p-modal text-justify">Primary Level (Cấp Ban Đầu/CBD) is the entry-level tier of Vietnam's professional-technical classification. Unlike CCB and CCS, assignment to this level is structural rather than score-based: it automatically applies to (a) health facilities without inpatient treatment, (b) commune health stations (trạm y tế xã, phường), and (c) area general clinics (phòng khám đa khoa khu vực) that do have inpatient beds. Facilities at this level are not subject to the Appendix V scoring exercise used for CCB and CCS.</p>
            <p class="p-modal text-justify"><strong>Note:</strong> This level applies to both public and private outpatient facilities. Commune health stations remain public and are supervised as part of the local health network, while private clinics, dental practices, laboratories, and family-medicine practices at this level operate independently under their own operating licenses.</p>
          </div>
          <div class="tab-pane fade" id="class-d-role" role="tabpanel" aria-labelledby="class-d-role-tab" tabindex="0">
            <ul>
              <li>Serve as the first point of contact for basic healthcare needs within a commune, ward, or local catchment area.</li>
              <li>Deliver preventive and public health programs, including maternal and child health, immunization, and health education.</li>
              <li>Provide basic outpatient consultation, minor treatment, and dental care where licensed.</li>
              <li>Refer patients to CCB or CCS facilities when a case exceeds their capability.</li>
              <li>Commune health stations may operate under the technical guidance of a district medical center (Trung tâm Y tế, TTYT) where one exists in the area.</li>
            </ul>
          </div>
          <div class="tab-pane fade" id="class-d-services" role="tabpanel" aria-labelledby="class-d-services-tab" tabindex="0">
            <ul>
              <li>General consultation, basic diagnosis, and treatment of common and uncomplicated conditions.</li>
              <li>Normal spontaneous delivery and basic maternal and newborn care, at commune health stations with the relevant capability.</li>
              <li>Minor outpatient procedures within the facility's licensed scope.</li>
              <li>Basic medicine dispensing and preventive health services.</li>
              <li>Typical catchment population of approximately 5,000 to 10,000 residents for a commune health station.</li>
            </ul>
            <p><strong>Diagnostic &amp; Support Infrastructure</strong></p>
            <ul>
              <li>Basic consultation and examination space.</li>
              <li>First-aid and basic emergency equipment appropriate to the facility type.</li>
              <li>Referral linkage to CCB or CCS facilities for cases requiring further care.</li>
            </ul>
            <p class="p-modal text-justify"><em><strong>Note:</strong> This classification is aligned with Decree No. 96/2023/NĐ-CP, Article 89.</em></p>
